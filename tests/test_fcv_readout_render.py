"""Part B (Word readout redesign) guards for the vendored design system.

Renders both route fixtures through the shared banner design system and asserts the
2026-10-26 decisions: amber "Be aware" box + "Draft - human review required" status
on BOTH routes, the duplicate generator line dropped, the ITS banner hyperlink
present and resolvable in the first-page header part, and the house bold-first-sentence
treatment applied to body paragraphs."""

import io
import json
from pathlib import Path

import pytest

from docx import Document

import build_fcv_readout
import build_climate_readout

FIXTURES = Path(__file__).resolve().parent / "fixtures"
ITS_URL = "https://fcvriskdashboardqa.worldbank.org/project-screener"
DRAFT = "Draft - human review required"


def _meta(route):
    return dict(
        title="FCV Recommendations Note",
        project_line="Test Project  ·  Country  ·  PAD  ·  26 October 2026",
        running_label="Test",
        classification="Official Use Only",
        generator="",
        disclaimer=DRAFT + ". Named approval of this version must be recorded separately before sharing.",
        its_url=ITS_URL,
    )


def _all_text(doc):
    out = [p.text for p in doc.paragraphs]
    for t in doc.tables:
        for row in t.rows:
            for c in row.cells:
                out += [p.text for p in c.paragraphs]
                for it in c.tables:
                    for r2 in it.rows:
                        for c2 in r2.cells:
                            out += [p.text for p in c2.paragraphs]
    return "\n".join(out)


def _header_has_its_link(doc):
    for sec in doc.sections:
        for hdr in (sec.first_page_header, sec.header):
            for rel in hdr.part.rels.values():
                if "project-screener" in str(rel.target_ref):
                    return True
    return False


def _render(builder, fixture_name, tmp_path):
    data = json.loads((FIXTURES / fixture_name).read_text(encoding="utf-8"))
    out = tmp_path / "out.docx"
    builder.render(data, _meta("x"), str(out))
    return Document(str(out))


def test_fcv_route_decisions(tmp_path):
    doc = _render(build_fcv_readout, "fcv_readout_sample.json", tmp_path)
    body = _all_text(doc)
    assert "Be aware" in body
    assert DRAFT in body
    assert _header_has_its_link(doc)
    # The duplicate "Generated by ..." generator line is dropped on screen/export.
    assert "Generated by" not in body


def test_climate_route_decisions(tmp_path):
    doc = _render(build_climate_readout, "climate_readout_sample.json", tmp_path)
    body = _all_text(doc)
    assert "Be aware" in body
    assert DRAFT in body
    assert _header_has_its_link(doc)
    assert "Generated by" not in body


def test_body_first_sentence_is_bold():
    """A multi-sentence body paragraph bolds only its opening sentence."""
    from fcv_docx_style import Report

    R = Report("fcv", _meta("x"))
    R.body("The project targets three regions. The rest of this paragraph is context.")
    para = R.doc.paragraphs[-1]
    runs = [r for r in para.runs if r.text.strip()]
    assert runs, "expected runs in the body paragraph"
    assert runs[0].font.bold is True
    assert runs[0].text.startswith("The project targets three regions.")
    assert any(r.font.bold in (False, None) for r in runs[1:]), "remainder should not be bold"


def test_split_first_sentence_single_sentence_is_fully_bold():
    from fcv_docx_style import _split_first_sentence

    lead, rest = _split_first_sentence("One complete sentence only.")
    assert lead == "One complete sentence only."
    assert rest == ""
